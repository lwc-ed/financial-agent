def parse_transaction(client: OpenAI, text: str) -> dict | None:
    resp = client.chat.completions.create(
        model="gpt-4o-mini",
        messages=[{"role": "user", "content": text}],
        tools=PARSE_TOOLS,
        tool_choice="required",
    )
    tool_call = resp.choices[0].message.tool_calls[0]
    intent = tool_call.function.name
    params = json.loads(tool_call.function.arguments)
    return {"type": intent, **params}


def main():
    from backend.database import SessionLocal
    from backend.models.record import Record

    client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))

    with SessionLocal() as db:
        ok, fail = 0, 0
        for text, ts_str in TRANSACTIONS:
            try:
                parsed = parse_transaction(client, text)
                db.add(Record(
                    line_user_id=LINE_USER_ID,
                    type=parsed["type"],
                    category=parsed["category"],
                    amount=parsed["amount"],
                    note=parsed.get("note") or text,
                    timestamp=datetime.strptime(ts_str, "%Y-%m-%d %H:%M"),
                ))
                print(f"✅ {ts_str} | {parsed['type']:7} | {parsed['category']:6} | {parsed['amount']:>6} | {text}")
                ok += 1
            except Exception as e:
                print(f"❌ {text} → {repr(e)}")
                fail += 1

        db.commit()
        print(f"\n完成：{ok} 筆成功，{fail} 筆失敗")


if __name__ == "__main__":
    main()
